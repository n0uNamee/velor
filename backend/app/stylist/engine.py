"""Deterministic catalog-only styling, validation and immutable replacement.

Free text is data. Unsupported hard requirements fail closed. This baseline does
not claim to understand arbitrary fashion prose or perform visual recognition.
"""
from collections import Counter
from decimal import Decimal
from hashlib import sha256
import json
import re
from typing import Iterable

from ..models import CATEGORIES, Constraint, Outfit, Product, StyleBrief
from .domain import (
    CompositionResult, OutfitValidationError, ProductFacts, StylingOptions,
    ValidationIssue, ValidationReport,
)

