def _norm(value: str) -> str:
    return " ".join(value.casefold().replace("ё", "е").split()).strip(" .!;")


def _canonical(field: str, value: str) -> str:
    value = _norm(value)
    return next((key for key, aliases in _ALIASES[field].items() if value in aliases), value)


def _slots(brief: StyleBrief, options: StylingOptions) -> tuple[str, ...]:
    return tuple(dict.fromkeys(options.item_slots if options.item_slots is not None else brief.categories))


def _catalog(products: list[Product], brief: StyleBrief, options: StylingOptions):
    issues = []
    index: dict[str, Product] = {}
    for product in products:
        if product.id in index:
            issues.append(ValidationIssue("duplicate_catalog_id", "В каталоге повторяется ID товара.", product.id))
        index[product.id] = product
    for product_id in options.owned_product_ids | options.pinned_product_ids:
        if product_id not in index or product_id in options.excluded_product_ids:
            issues.append(ValidationIssue("unavailable_required_product", "Закреплённый или свой товар отсутствует в разрешённом каталоге.", product_id))
    slots = _slots(brief, options)
    if not slots or any(slot not in CATEGORIES for slot in slots):
        issues.append(ValidationIssue("invalid_item_slots", "Нужен непустой список известных категорий вещей."))
    for category in brief.sizes or {}:
        if category not in CATEGORIES:
            issues.append(ValidationIssue("unsupported_size_key", "Размер должен относиться к известной категории."))
    return index, tuple(issues)


def _hard_rules(brief: StyleBrief):
    rules: list[tuple[str, str, bool, str]] = []
    issues = []
    for item in (*brief.constraints, *brief.exclusions, *brief.preferences):
        if item.strength != "hard":
            continue
        text = _norm(item.text)
        # These are generated by brief.py from the corresponding structured field.
        if brief.budget_rub is not None and text == _norm(f"Общий бюджет: до {brief.budget_rub:g} ₽"):
            continue
        if brief.sizes and text == _norm("Размеры: " + ", ".join(f"{k}: {v}" for k, v in brief.sizes.items())):
            continue
        match = re.fullmatch(r"(?:без|исключить|не хочу|не надо|никаких|no|without|avoid)\s+(.+)", text)
        negate = bool(match)
        if not match:
            match = re.fullmatch(r"(?:только|обязательно|only|must be|required)\s+(.+)", text)
        target = match.group(1).strip() if match else ""
        found = None
        for field, aliases in _ALIASES.items():
            for canonical, values in aliases.items():
                if target in values:
                    found = (field, canonical, negate, item.text)
                    break
            if found:
                break
        if found:
            rules.append(found)
        else:
            issues.append(ValidationIssue("unsupported_hard_constraint", f"Не могу подтвердить строгое условие по данным каталога: {item.text}"))
    return rules, tuple(issues)


def _product_issues(product: Product, brief: StyleBrief, options: StylingOptions, rules) -> list[ValidationIssue]:
    issues = []
    pid = product.id
    if pid in options.excluded_product_ids:
        issues.append(ValidationIssue("excluded_product", "Товар исключён пользователем.", pid))
    allowed_verification = {"verified", "demo"} if brief.mode == "demo" else {"verified"}
    if product.verification not in allowed_verification or (brief.mode == "live" and product.is_demo):
        issues.append(ValidationIssue("unverified_product", "Товар не прошёл требуемую проверку каталога.", pid))
    explicit_demo = brief.mode == "demo" and (product.is_demo or product.verification == "demo")
    if product.availability != "in_stock" and pid not in options.owned_product_ids and not (explicit_demo and product.availability == "unknown"):
        issues.append(ValidationIssue("unavailable_product", "Наличие товара не подтверждено.", pid))
    size = (brief.sizes or {}).get(product.category)
    if size is not None and _norm(size) not in {_norm(value) for value in product.sizes}:
        issues.append(ValidationIssue("size_unavailable", "Запрошенный размер не подтверждён для товара.", pid))
    if brief.budget_rub is not None and product.price_rub is None and pid not in options.owned_product_ids:
        issues.append(ValidationIssue("unknown_price", "Неизвестная цена не позволяет проверить общий бюджет.", pid))
    facts = options.facts.get(pid, ProductFacts())
    for field, expected, negate, source in rules:
        values = getattr(facts, field)
        if values is None:
            issues.append(ValidationIssue("unknown_hard_attribute", f"Не подтверждено условие «{source}»: {field} неизвестно.", pid))
            continue
        canonical = {_canonical(field, value) for value in values}
        if any(value not in _ALIASES[field] for value in canonical):
            issues.append(ValidationIssue("unknown_hard_attribute", f"Нормализованные {field} не позволяют подтвердить условие «{source}».", pid))
            continue
        satisfied = expected not in canonical if negate else bool(canonical) and canonical == {expected}
        if not satisfied:
            issues.append(ValidationIssue("hard_constraint_violation", f"Товар не соответствует условию «{source}».", pid))
    return issues


def _sum_prices(products: Iterable[Product], owned: frozenset[str] = frozenset()) -> float | None:
    products = list(products)
    prices = [Decimal(str(product.price_rub)) for product in products if product.id not in owned and product.price_rub is not None]
    if any(product.price_rub is None for product in products if product.id not in owned):
        return None
    return float(sum(prices, Decimal(0)))


def validate_outfit(outfit: Outfit, brief: StyleBrief, products: list[Product], *, options: StylingOptions | None = None) -> ValidationReport:
    """Validate exact catalog membership and all known hard constraints, no I/O."""
    options = options or StylingOptions()
    index, catalog_issues = _catalog(products, brief, options)
    rules, hard_issues = _hard_rules(brief)
    issues = list(catalog_issues + hard_issues)
    selected = []
    if len(set(outfit.product_ids)) != len(outfit.product_ids):
        issues.append(ValidationIssue("duplicate_outfit_product", "Один товар нельзя повторять в образе."))
    for pid in outfit.product_ids:
        if pid not in index:
            issues.append(ValidationIssue("catalog_membership", "Товар отсутствует в разрешённом каталоге.", pid))
            continue
        product = index[pid]
        selected.append(product)
        issues.extend(_product_issues(product, brief, options, rules))
    actual = Counter(product.category for product in selected)
    expected = Counter(_slots(brief, options))
    if actual != expected:
        issues.append(ValidationIssue("item_slots_mismatch", "Образ должен содержать ровно одну вещь каждой запрошенной категории."))
    for pid in options.pinned_product_ids - set(outfit.product_ids):
        issues.append(ValidationIssue("pinned_product_missing", "Закреплённая вещь должна сохраниться.", pid))
    total = _sum_prices(selected)
    purchase = _sum_prices(selected, options.owned_product_ids)
    if brief.budget_rub is not None and purchase is not None and Decimal(str(purchase)) > Decimal(str(brief.budget_rub)):
        issues.append(ValidationIssue("budget_exceeded", "Общая стоимость покупок превышает бюджет."))
    unknowns = list(brief.unknowns)
    if any(product.price_rub is None for product in selected):
        unknowns.append("Для части вещей цена неизвестна; полная стоимость образа не подтверждена.")
    if not brief.sizes:
        unknowns.append("Размеры не заданы: посадка и подходящий вариант не подтверждены.")
    if not options.facts:
        unknowns.append("Цвета и материалы не подтверждены структурированными данными каталога.")
    return ValidationReport(not issues, tuple(issues), total, purchase, tuple(dict.fromkeys(unknowns)))


def _tokens(value: str) -> set[str]:
    return set(re.findall(r"[\w-]{3,}", _norm(value)))


def _soft_score(product: Product, brief: StyleBrief, options: StylingOptions) -> float:
    facts = options.facts.get(product.id, ProductFacts())
    content = _tokens(" ".join((product.title, *(facts.colors or ()), *(facts.materials or ()), *(facts.tags or ()))))
    score = sum(len(content & _tokens(item.text)) * item.confidence for item in brief.preferences if item.strength == "soft")
    return score + (0.25 if product.id in options.owned_product_ids else 0)


def _coherence(selected: tuple[Product, ...], options: StylingOptions) -> float:
    colors = Counter(color for product in selected for color in (options.facts.get(product.id, ProductFacts()).colors or ()))
    tags = Counter(tag for product in selected for tag in (options.facts.get(product.id, ProductFacts()).tags or ()))
    return sum(max(0, count - 1) for count in colors.values()) * 0.5 + sum(max(0, count - 1) for count in tags.values()) * 0.4


def _explanation(selected: list[Product], brief: StyleBrief, options: StylingOptions, report: ValidationReport) -> str:
    parts = ["Подбор по детерминированным правилам VÉLOR; реальная языковая модель не вызывалась."]
    if brief.mode == "demo" or any(p.is_demo or p.verification == "demo" for p in selected):
        parts.append("Демонстрационный режим: ассортимент и наличие не являются результатом live-поиска.")
    parts.append("Каждая вещь взята из разрешённого каталога, категории и известные строгие условия проверены.")
    if report.purchase_price_rub is not None:
        parts.append(f"Стоимость новых покупок: {report.purchase_price_rub:g} ₽.")
    if any(p.id in options.owned_product_ids for p in selected):
        parts.append("Подтверждённые свои вещи сохранены; повторная покупка не включена в бюджет.")
    matched = []
    for preference in brief.preferences:
        if preference.strength == "soft" and any(_soft_score(p, brief.model_copy(update={"preferences": [preference]}), options) > (0.25 if p.id in options.owned_product_ids else 0) for p in selected):
            matched.append(preference.text)
    if matched:
        parts.append("Мягкие пожелания частично совпали с описанием товаров: " + "; ".join(matched[:3]) + ".")
    else:
        parts.append("Мягкое стилевое совпадение не подтверждено описаниями; выбрано совместимое сочетание категорий.")
    parts.extend(report.unknowns[:5])
    return " ".join(parts)


def _make_outfit(request_id: str, selected: list[Product], brief: StyleBrief, options: StylingOptions, ordinal: int) -> Outfit:
    signature = json.dumps([request_id, sorted(product.id for product in selected)], ensure_ascii=False)
    outfit = Outfit(id="outfit_" + sha256(signature.encode()).hexdigest()[:20], request_id=request_id,
                    title=f"VÉLOR · образ {ordinal}", product_ids=[product.id for product in selected],
                    explanation="", render_disclaimer=SCHEMATIC_DISCLAIMER)
    report = validate_outfit(outfit, brief, selected, options=StylingOptions(
        excluded_product_ids=options.excluded_product_ids, owned_product_ids=options.owned_product_ids & set(outfit.product_ids),
        pinned_product_ids=options.pinned_product_ids, item_slots=options.item_slots, facts=options.facts,
        max_outfits=options.max_outfits))
    return outfit.model_copy(update={"explanation": _explanation(selected, brief, options, report)})


def compose_outfits_result(request_id: str, brief: StyleBrief, products: list[Product], *, options: StylingOptions | None = None) -> CompositionResult:
    """Bounded deterministic beam search; never fills missing slots with invented IDs."""
    options = options or StylingOptions()
    index, issues = _catalog(products, brief, options)
    rules, rule_issues = _hard_rules(brief)
    issues += rule_issues
    is_demo = brief.mode == "demo"
    if issues:
        return CompositionResult([], issues, is_demo=is_demo)
    eligible = {pid: p for pid, p in index.items() if not _product_issues(p, brief, options, rules)}
    slots = _slots(brief, options)
    groups = []
    for slot in slots:
        pins = [eligible[pid] for pid in options.pinned_product_ids if pid in eligible and eligible[pid].category == slot]
        choices = pins if pins else [p for p in eligible.values() if p.category == slot]
        if len(pins) > 1 or any(pid not in eligible for pid in options.pinned_product_ids):
            return CompositionResult([], (ValidationIssue("invalid_pinned_product", "Закреплённые вещи не проходят ограничения или конфликтуют по категории."),), is_demo=is_demo)
        if not choices:
            rejected = tuple(issue for p in index.values() if p.category == slot for issue in _product_issues(p, brief, options, rules))
            return CompositionResult([], (ValidationIssue("missing_item_slot", f"Нет подтверждённой вещи для категории {slot}."), *rejected[:20]), is_demo=is_demo)
        groups.append(sorted(choices, key=lambda p: (-_soft_score(p, brief, options), p.price_rub if p.price_rub is not None else float("inf"), p.id)))
    beam: list[tuple[Product, ...]] = [()]
    for choices in groups:
        candidates = []
        for partial in beam:
            for product in choices:
                selected = (*partial, product)
                cost = _sum_prices(selected, options.owned_product_ids)
                if brief.budget_rub is not None and cost is not None and Decimal(str(cost)) > Decimal(str(brief.budget_rub)):
                    continue
                candidates.append(selected)
        candidates.sort(key=lambda selected: (
            -sum(_soft_score(p, brief, options) for p in selected) - _coherence(selected, options),
            _sum_prices(selected, options.owned_product_ids) if _sum_prices(selected, options.owned_product_ids) is not None else float("inf"),
            tuple(p.id for p in selected)))
        beam = candidates[:128]
    if not beam:
        return CompositionResult([], (ValidationIssue("budget_exceeded", "Нет полного образа в пределах общего бюджета."),), is_demo=is_demo)
    outfits, seen = [], set()
    for selected in beam:
        key = frozenset(p.id for p in selected)
        if key in seen:
            continue
        candidate = _make_outfit(request_id, list(selected), brief, options, len(outfits) + 1)
        report = validate_outfit(candidate, brief, products, options=options)
        if not report.valid:
            continue
        seen.add(key)
        outfits.append(candidate)
        if len(outfits) >= max(1, min(options.max_outfits, 6)):
            break
    return CompositionResult(outfits, () if outfits else (ValidationIssue("no_valid_outfit", "Ни один образ не прошёл проверку."),), is_demo=is_demo)


def compose_outfits(request_id: str, brief: StyleBrief, products: list[Product], *, options: StylingOptions | None = None) -> list[Outfit]:
    return compose_outfits_result(request_id, brief, products, options=options).outfits


def replace_outfit_item(outfit: Outfit, brief: StyleBrief, products: list[Product], old_product_id: str,
                        new_product_id: str, expected_revision: int, *, options: StylingOptions | None = None) -> Outfit:
    """Create a validated new revision; never mutate the input/saved old revision."""
    options = options or StylingOptions()
    if expected_revision != outfit.revision:
        raise OutfitValidationError((ValidationIssue("stale_revision", "Образ уже изменён; обновите ожидаемую ревизию."),))
    if old_product_id not in outfit.product_ids:
        raise OutfitValidationError((ValidationIssue("old_product_missing", "Заменяемая вещь отсутствует в образе."),))
    if old_product_id in options.pinned_product_ids:
        raise OutfitValidationError((ValidationIssue("pinned_product", "Закреплённую вещь нельзя заменить."),))
    if new_product_id == old_product_id:
        raise OutfitValidationError((ValidationIssue("unchanged_product", "Новая вещь должна отличаться от заменяемой."),))
    index, issues = _catalog(products, brief, options)
    if issues:
        raise OutfitValidationError(issues)
    if old_product_id not in index or new_product_id not in index:
        raise OutfitValidationError((ValidationIssue("catalog_membership", "Обе вещи должны существовать в разрешённом каталоге."),))
    if index[old_product_id].category != index[new_product_id].category:
        raise OutfitValidationError((ValidationIssue("category_mismatch", "Замена должна занимать ту же категорию."),))
    candidate = outfit.model_copy(update={
        "product_ids": [new_product_id if pid == old_product_id else pid for pid in outfit.product_ids],
        "revision": outfit.revision + 1, "render_revision": None, "render_status": "pending",
        "render_url": None, "saved": False, "render_disclaimer": SCHEMATIC_DISCLAIMER,
    }, deep=True)
    report = validate_outfit(candidate, brief, products, options=options)
    if not report.valid:
        raise OutfitValidationError(report.issues)
    return candidate.model_copy(update={"explanation": _explanation([index[pid] for pid in candidate.product_ids], brief, options, report)})
